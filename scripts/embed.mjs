#!/usr/bin/env node
/** Rebuild src/dictionaries.js and ModuleLoader src/client.browser.js from dicts/zh-Hant/*.json */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(readFileSync(join(root, 'dicts/zh-Hant/manifest.json'), 'utf8'));

const dictObject = {};
for (const [ns, meta] of Object.entries(manifest.namespaces)) {
  dictObject[ns] = JSON.parse(readFileSync(join(root, 'dicts/zh-Hant', meta.file), 'utf8'));
}

const LOCALE_ID = manifest.locale;
const LOCALE_LABEL = '繁體中文（香港）';
const FALLBACK = 'zh';
const DICT_JSON = JSON.stringify(dictObject);

// --- readable ESM for Node check ---
const esm = [];
esm.push('/** Auto-generated from dicts/zh-Hant — do not edit by hand; re-run scripts/embed.mjs */');
esm.push(`export const LOCALE_ID = ${JSON.stringify(LOCALE_ID)};`);
esm.push(`export const LOCALE_LABEL = ${JSON.stringify(LOCALE_LABEL)};`);
esm.push(`export const FALLBACK = ${JSON.stringify(FALLBACK)};`);
esm.push('/** @type {Record<string, Record<string, string>>} */');
esm.push('export const dictionaries = {');
for (const [ns, dict] of Object.entries(dictObject)) {
  const body = JSON.stringify(dict, null, 2)
    .split('\n')
    .map((l, i) => (i === 0 ? l : `  ${l}`))
    .join('\n');
  esm.push(`  ${JSON.stringify(ns)}: ${body},`);
}
esm.push('};');
esm.push('');
writeFileSync(join(root, 'src/dictionaries.js'), esm.join('\n'));
console.log(`[embed] wrote src/dictionaries.js (${Object.keys(dictObject).length} ns)`);

// --- ModuleLoader browser client (Web GUI loads exports["./client"] this way) ---
const browser = `/**
 * agent-ui-zh-hant — browser half (ModuleLoader).
 * Auto-generated by scripts/embed.mjs — do not edit by hand.
 *
 * Web GUI loads ./client via window.__ModuleLoader__.load({ id, factory }),
 * NOT as an ESM export apply. Host half is src/index.js (empty apply).
 */
window.__ModuleLoader__.load({
\tid: 'agent-ui-zh-hant',
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
\t\tvar DICTIONARIES = ${DICT_JSON};
\t\tvar LANGUAGE = { id: ${JSON.stringify(LOCALE_ID)}, label: ${JSON.stringify(LOCALE_LABEL)}, fallback: ${JSON.stringify(FALLBACK)} };
\t\tfunction apply(ctx) {
\t\t\tvar locale = ctx.locale;
\t\t\tvar registered = false;
\t\t\ttry {
\t\t\t\tctx.effect(function () {
\t\t\t\t\treturn locale.addLanguage(LANGUAGE);
\t\t\t\t}, 'agent-ui-zh-hant: language');
\t\t\t\tregistered = true;
\t\t\t} catch (error) {
\t\t\t\tconsole.warn('agent-ui-zh-hant: another pack already provides ' + LANGUAGE.id + '; skipping', error);
\t\t\t}
\t\t\tif (!registered) return;
\t\t\tvar namespaces = Object.keys(DICTIONARIES);
\t\t\tctx.effect(function () {
\t\t\t\tvar disposers = namespaces.map(function (name) {
\t\t\t\t\treturn locale.register(name, LANGUAGE.id, DICTIONARIES[name]);
\t\t\t\t});
\t\t\t\treturn function () {
\t\t\t\t\tfor (var i = disposers.length - 1; i >= 0; i--) disposers[i]();
\t\t\t\t};
\t\t\t}, 'agent-ui-zh-hant: dictionaries');
\t\t}
\t\texports.LANGUAGE = LANGUAGE;
\t\texports.DICTIONARIES = DICTIONARIES;
\t\texports.apply = apply;
\t\t// Cordis service inject name — NOT the package id.
\t\texports.inject = ['locale'];
\t\treturn module.exports;
\t}
});
`;
writeFileSync(join(root, 'src/client.browser.js'), browser);
console.log(`[embed] wrote src/client.browser.js (ModuleLoader id=agent-ui-zh-hant)`);
